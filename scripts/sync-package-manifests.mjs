#!/usr/bin/env node
/**
 * Refresh winget + Homebrew packaging files from a GitHub Release tag.
 *
 * Usage: node scripts/sync-package-manifests.mjs v0.8.0
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  GITHUB_REPO,
  dmgUrl,
  parseTagVersion,
  pickMacDmg,
  pickWindowsInstaller,
  sha256FromDigest,
} from './lib/release-assets.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const tag = process.argv[2];
if (!tag) {
  console.error('Usage: node scripts/sync-package-manifests.mjs <tag>  (e.g. v0.8.0)');
  process.exit(1);
}

const version = parseTagVersion(tag);
const res = await fetch(`https://api.github.com/repos/${GITHUB_REPO}/releases/tags/${encodeURIComponent(tag)}`, {
  headers: { Accept: 'application/vnd.github+json', 'User-Agent': 'deco-sync-manifests' },
});
if (!res.ok) {
  console.error(`GitHub API ${res.status} for ${tag}`);
  process.exit(1);
}
/** @type {{ assets: import('./lib/release-assets.mjs').GhAsset[] }} */
const release = await res.json();
const assets = release.assets ?? [];

const win = pickWindowsInstaller(assets);
const dmg = pickMacDmg(assets);

const wingetDir = path.join(
  root,
  'packaging',
  'winget',
  'manifests',
  'd',
  'De',
  'Dendro-X0.Deco',
  version,
);

if (win) {
  const sha = sha256FromDigest(win.asset.digest);
  if (!sha) {
    console.error('Windows installer missing sha256 digest on GitHub asset');
    process.exit(1);
  }
  await mkdir(wingetDir, { recursive: true });
  const id = 'Dendro-X0.Deco';
  await writeFile(
    path.join(wingetDir, `${id}.yaml`),
    `# Generated by scripts/sync-package-manifests.mjs — copy to microsoft/winget-pkgs on release
PackageIdentifier: ${id}
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.6.0
`,
  );
  await writeFile(
    path.join(wingetDir, `${id}.locale.en-US.yaml`),
    `PackageIdentifier: ${id}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: Dendro-X0
PublisherUrl: https://github.com/Dendro-X0
PublisherSupportUrl: https://github.com/Dendro-X0/Deco/issues
PackageName: Deco
PackageUrl: https://github.com/Dendro-X0/Deco
License: MIT
LicenseUrl: https://github.com/Dendro-X0/Deco/blob/main/LICENSE
ShortDescription: Disk cleanup for developer machines
Description: |-
  Deco scans developer workspaces for reclaimable build artifacts and caches,
  with a safety-first review workflow and quarantine-first cleanup.
Moniker: deco
Tags:
- developer
- cleanup
- disk
ManifestType: defaultLocale
ManifestVersion: 1.6.0
`,
  );
  await writeFile(
    path.join(wingetDir, `${id}.installer.yaml`),
    `PackageIdentifier: ${id}
PackageVersion: ${version}
InstallerType: ${win.kind}
Scope: user
InstallModes:
- interactive
- silent
UpgradeBehavior: install
ReleaseDate: ${new Date().toISOString().slice(0, 10)}
Installers:
- Architecture: x64
  InstallerUrl: ${win.asset.browser_download_url}
  InstallerSha256: ${sha}
  InstallerLocale: en-US
  Platform:
  - Windows.Desktop
ManifestType: installer
ManifestVersion: 1.6.0
`,
  );
  console.log(`Wrote winget manifests → packaging/winget/manifests/d/De/Dendro-X0.Deco/${version}/`);
} else {
  console.warn(`WARN: No Windows MSI/EXE on ${tag} — winget manifests not updated`);
}

const brewPath = path.join(root, 'packaging', 'homebrew', 'Casks', 'deco.rb');
if (dmg) {
  const sha = sha256FromDigest(dmg.digest);
  if (!sha) {
    console.error('macOS dmg missing sha256 digest');
    process.exit(1);
  }
  await mkdir(path.dirname(brewPath), { recursive: true });
  const ruby = `# Generated by scripts/sync-package-manifests.mjs
cask "deco" do
  version "${version}"
  sha256 "${sha.toLowerCase()}"

  url "${dmgUrl(version, dmg.name)}"
  name "Deco"
  desc "Disk cleanup for developer machines"
  homepage "https://github.com/${GITHUB_REPO}"

  depends_on macos: ">= :monterey"
  depends_on arch: :arm64

  app "Deco.app"

  zap trash: [
    "~/Library/Application Support/com.dendrox.deco",
  ]
end
`;
  await writeFile(brewPath, ruby);
  console.log(`Wrote ${path.relative(root, brewPath)}`);
} else {
  console.warn(`WARN: No macOS .dmg on ${tag} — Homebrew cask not updated`);
}

if (!win && !dmg) {
  process.exit(1);
}
